// Regenerates lib/custom-data-demo.ts, the upload behind the "custom data" gallery example.
//
// The demo stands in for a clinician-curated annotation: every sample of luad_mskimpact_2021
// (93 patients, 186 primary/metastasis samples) gets a BIOPSY_SITE, grouped from the study's own
// SAMPLE_TYPE and free-text METASTATIC_SITE the way a reviewer would group them. Deriving it
// from real fields keeps the example's numbers real; the example's note says where it came from.
//
// Run: node --env-file=.env.local scripts/gen-custom-demo.ts
import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";
import { chQuery } from "../lib/ch.ts";
import { studyRouting } from "../lib/federation.ts";
import { sq } from "../lib/compiler.ts";

const STUDY = "luad_mskimpact_2021";
const conn = (await studyRouting()).get(STUDY);
if (!conn) throw new Error(STUDY + " is not routed");

const GROUPS: [string, RegExp][] = [
  ["CNS met", /brain|cerebell|dura|csf/],
  ["Lymph node met", /lymph/],
  ["Pleural/pericardial met", /pleura|pericard/],
  ["Liver met", /liver/],
  ["Bone met", /bone|rib|sternum|vertebr|epidural/]
];
const siteOf = (sampleType: string, metSite: string): string => {
  if (/primary|recurrence/i.test(sampleType)) return "Primary";
  const m = metSite.toLowerCase();
  return GROUPS.find(([, re]) => re.test(m))?.[0] ?? "Other met";
};

const r = await chQuery<{ patient: string; sample: string; st: string; ms: string }>(
  "SELECT patient_stable_id AS patient, sample_stable_id AS sample,\n" +
  "       anyIf(cd.attribute_value, cd.attribute_name = 'SAMPLE_TYPE') AS st,\n" +
  "       anyIf(cd.attribute_value, cd.attribute_name = 'METASTATIC_SITE') AS ms\n" +
  "FROM " + conn.db + ".sample_derived sd\n" +
  "LEFT JOIN " + conn.db + ".clinical_data_derived cd ON cd.sample_unique_id = sd.sample_unique_id AND cd.cancer_study_identifier = " + sq(STUDY) + "\n" +
  "WHERE sd.cancer_study_identifier = " + sq(STUDY) + "\n" +
  "GROUP BY patient, sample ORDER BY patient, sample", conn);

const rows = r.data.map((x) => ({ study: STUDY, patient: x.patient, sample: x.sample, values: [siteOf(x.st, x.ms)] }));
const counts = new Map<string, number>();
for (const x of rows) counts.set(x.values[0], (counts.get(x.values[0]) || 0) + 1);

const out = `// GENERATED by scripts/gen-custom-demo.ts — do not edit. ${rows.length} samples of ${STUDY}:
// ${[...counts].sort((a, b) => b[1] - a[1]).map(([k, n]) => k + " " + n).join(", ")}.
import type { CustomDataset } from "./custom-data-names.ts";

export const LUAD_BIOPSY_SITE_DEMO: CustomDataset = ${JSON.stringify({
  id: "luad-biopsy-site", name: "LUAD biopsy site (demo)", level: "sample",
  columns: [{ name: "BIOPSY_SITE", datatype: "STRING" }]
}).slice(0, -1)}, "rows": [
${rows.map((x) => "  " + JSON.stringify(x)).join(",\n")}
] };
`;
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
writeFileSync(join(root, "lib", "custom-data-demo.ts"), out);
console.log("wrote lib/custom-data-demo.ts:", rows.length, "samples;", [...counts].map(([k, n]) => k + "=" + n).join(", "));

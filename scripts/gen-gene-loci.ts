// Writes lib/gene-loci-data.ts: where each protein-coding gene lies on hg19 and hg38, for the
// segments view's zoom to a gene. The warehouse records a gene's chromosome and cytoband but not its
// coordinates (reference_genome_gene.start/end are 0 for every gene, here and on cbioportal.org), so
// the portal's CN Segments tab zooms through IGV, which looks the symbol up in its own refGene
// annotation. This reads the same files igv.js loads for those genome ids and keeps, per symbol, the
// span of its RefSeq mRNAs (NM_*) on chromosomes 1-22, X and Y — a gene on both X and Y (the
// pseudoautosomal genes) keeps X. Run it again to refresh: `node scripts/gen-gene-loci.ts`.
import { writeFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";

const SOURCE = (build: string) => "https://s3.amazonaws.com/igv.org.genomes/" + build + "/refGene.sorted.txt.gz";
const CHROMS = [...Array.from({ length: 22 }, (_, i) => String(i + 1)), "X", "Y"];

/** a build's genes as the data file holds them: per chromosome, "SYMBOL,start,length" with start a hex delta from the gene before */
export function encodeLoci(rows: { gene: string; chrom: string; start: number; end: number }[]): string {
  const byChrom = new Map<string, { gene: string; start: number; end: number }[]>();
  for (const r of rows) {
    const list = byChrom.get(r.chrom) || [];
    list.push(r);
    byChrom.set(r.chrom, list);
  }
  return CHROMS.filter((c) => byChrom.has(c)).map((c) => {
    let prev = 0;
    const genes = byChrom.get(c)!.sort((a, b) => a.start - b.start || a.gene.localeCompare(b.gene)).map((g) => {
      const s = g.gene + "," + (g.start - prev).toString(16) + "," + (g.end - g.start).toString(16);
      prev = g.start;
      return s;
    });
    return c + ":" + genes.join(";");
  }).join("\n");
}

/** per symbol, the span of its NM_ transcripts on its chromosome (X before Y) */
export function spansOf(refGene: string): { gene: string; chrom: string; start: number; end: number }[] {
  const spans = new Map<string, { gene: string; chrom: string; start: number; end: number }>();
  for (const line of refGene.split("\n")) {
    const f = line.split("\t");
    if (f.length < 13 || !f[1].startsWith("NM_")) continue;
    const chrom = f[2].replace(/^chr/, "");
    if (!CHROMS.includes(chrom)) continue;
    const gene = f[12], start = Number(f[4]), end = Number(f[5]);
    const cur = spans.get(gene);
    if (cur && cur.chrom !== chrom) {
      if (CHROMS.indexOf(chrom) < CHROMS.indexOf(cur.chrom)) spans.set(gene, { gene, chrom, start, end });
      continue;
    }
    spans.set(gene, cur ? { gene, chrom, start: Math.min(cur.start, start), end: Math.max(cur.end, end) } : { gene, chrom, start, end });
  }
  return [...spans.values()];
}

if (process.argv[1] && /gen-gene-loci/.test(process.argv[1])) {
  const out: Record<string, string> = {};
  for (const build of ["hg19", "hg38"]) {
    const res = await fetch(SOURCE(build));
    if (!res.ok) throw new Error(SOURCE(build) + ": " + res.status);
    const rows = spansOf(gunzipSync(Buffer.from(await res.arrayBuffer())).toString("utf8"));
    out[build] = encodeLoci(rows);
    process.stdout.write(build + ": " + rows.length + " genes\n");
  }
  writeFileSync("lib/gene-loci-data.ts",
    "// Generated by scripts/gen-gene-loci.ts from IGV's refGene annotation (" + SOURCE("<build>") + ") — do not edit.\n" +
    "// Per build, one line per chromosome: \"<chrom>:\" then \"SYMBOL,start,length;\" with start (0-based, hex) a delta\n" +
    "// from the gene before on the chromosome and length (hex) in bases. Read through lib/gene-loci.ts.\n" +
    "export const GENE_LOCI_DATA: Record<\"hg19\" | \"hg38\", string> = {\n" +
    Object.entries(out).map(([b, s]) => "  " + b + ": " + JSON.stringify(s) + ",\n").join("") + "};\n");
  process.stdout.write("wrote lib/gene-loci-data.ts\n");
}
